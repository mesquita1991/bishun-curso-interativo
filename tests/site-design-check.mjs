import fs from 'node:fs';import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const pages=['index.html','trilha.html','manual.html','estudar.html','mapa.html','base.html','imersao.html','validacao.html','laboratorio.html','catalogo.html','avaliacao.html','aulas.html','historico.html',...Array.from({length:9},(_,i)=>'etapa-'+(i+1)+'.html')];
const targets=['./','trilha.html','mapa.html','laboratorio.html','catalogo.html','avaliacao.html','aulas.html'];
const labels=['Início','Aprender','Etapas','Escrita','Consultar','Revisão','Biblioteca'];
const shell=new Set(),footers=new Set(),broken=[],pageMeta=[];
function navLinks(html,pattern){const m=html.match(pattern);assert.ok(m,'Missing navigation');return [...m[1].matchAll(/<a\b[^>]*href="([^"]+)"[^>]*>([^<]+)<\/a>/g)].map(x=>({href:x[1],name:x[2]}))}
for(const file of pages){
 const html=read(file);
 assert.ok(html.includes('<body class="bishun-site'),'Shared body absent: '+file);
 assert.ok(html.includes('interface.css?v=7.1.0'),'Shared design stylesheet absent: '+file);
 assert.equal((html.match(/<header class="topbar site-header">/g)||[]).length,1,'Duplicated or missing header: '+file);
 assert.equal((html.match(/<footer class="foot site-footer">/g)||[]).length,1,'Duplicated or missing footer: '+file);
 assert.ok(html.includes('<main id="conteudo"'),'Missing skip-link destination: '+file);
 assert.equal((html.match(/<h1\b/g)||[]).length,1,'Must have exactly one main heading: '+file);
 assert.ok(html.match(/<title>[^<]+ \| Bǐshùn<\/title>/),'Unstandardized SEO title: '+file);
 assert.ok(html.includes('rel="canonical"'),'Canonical URL missing: '+file);
 assert.ok(!html.includes('href="curso.html"'),'Legacy link: '+file);
 assert.ok(html.includes('<details class="site-mobile-menu"><summary>Menu</summary>'),'Mobile navigation missing: '+file);
 const desk=navLinks(html,/<nav class="topnav"[^>]*>([\s\S]*?)<\/nav>/);
 const mobile=navLinks(html,/<nav aria-label="Navegação no celular">([\s\S]*?)<\/nav>/);
 assert.deepEqual(desk.map(x=>x.href),targets,'Desktop nav order: '+file);
 assert.deepEqual(mobile.map(x=>x.href),targets,'Mobile nav order: '+file);
 assert.deepEqual(desk.map(x=>x.name),labels,'Desktop nav labels: '+file);
 assert.deepEqual(mobile.map(x=>x.name),labels,'Mobile nav labels: '+file);
 shell.add(desk.map(x=>x.href+'='+x.name).join('|'));
 const footer=html.match(/<footer class="foot site-footer">([\s\S]*?)<\/footer>/)[1];
 footers.add(footer);
 assert.ok(footer.includes('Seu progresso fica neste navegador.'),'Missing progress privacy notice: '+file);
 const current=new RegExp('href="([^"]+)" aria-current="page"','g');
 for(const m of html.matchAll(current))assert.equal(m[1],file==='index.html'?'./':file,'Misleading current-page link: '+file);
 assert.ok(file==='index.html'||html.includes('class="breadcrumb"'),'Breadcrumb missing: '+file);
 for(const m of html.matchAll(/\bhref="([^"]+)"/g)){const href=m[1].replaceAll('&amp;','&');if(href.startsWith('#')||href.includes('://')||href.startsWith('mailto:'))continue;const pathname=href.split(/[?#]/)[0];if(pathname==='.'||pathname==='./'||pathname===''||pathname==='/')continue;if(!fs.existsSync(pathname))broken.push({from:file,to:href});}
 pageMeta.push({file,htmlBytes:Buffer.byteLength(html)});
}
const home=read('index.html'),homeApp=read('portal.js'),homeCSS=read('jornada.css');
assert.ok(home.includes('Curso integral · 9 etapas')&&home.includes('Curso de 3 meses · 90 dias'),'Percursos ausentes');
assert.ok(home.includes('id="percursos"')&&home.includes('id="semanas90"'),'Âncoras ausentes');
assert.ok(home.includes('href="mapa.html"')&&home.includes('href="manual.html?dia=1"'),'Destinos ausentes');
assert.equal((home.match(/class="journey-choice journey-choice-/g)||[]).length,2);
assert.equal((home.match(/class="stage-card"/g)||[]).length,9);
assert.ok(homeApp.includes('Consolidar e demonstrar')&&homeApp.includes('topics.forEach'));
assert.ok(homeCSS.includes('.journey-choice-integral')&&homeCSS.includes('.journey-choice-90'));
assert.ok(home.includes('302 lições')&&home.includes('id="portalResume"'));
assert.ok(read('plataforma.js').includes('initNavigation()')&&read('estudar.js').includes('data-exam-flow')&&read('trilha-v9.js').includes('setLocation(push=false)'),'Regressão das correções de navegação');
assert.equal(shell.size,1,'Header navigation differs between pages');
assert.equal(footers.size,1,'Footers differ between pages');
assert.deepEqual(broken,[],'Some local links have no file destination');
assert.ok(!read('interface.css').includes('@import'),'Design system must not require a remote font');
const pkg=JSON.parse(read('package.json'));assert.equal(pkg.version,'9.0.0');
assert.equal(JSON.parse(read('release-manifest.json')).version,pkg.version);
assert.ok(read('sw.js').includes('bishun-offline-9.0.0'),'Cache version must be updated');
assert.ok(read('sw.js').includes('./interface.css?v=7.1.0'),'Shared UI must be part of offline shell');
assert.ok(read('estudar.html').includes('id="studentGoal"'),'Student guidance must remain');
assert.ok(read('etapa.js').includes('Estudar esta unidade · 4 atividades'),'Existing stage links remain');
console.log(JSON.stringify({ok:true,pages:pages.length,sharedHeaders:shell.size,sharedFooters:footers.size,missingLocalLinks:0,version:pkg.version,largestHTMLBytes:Math.max(...pageMeta.map(x=>x.htmlBytes))}));
