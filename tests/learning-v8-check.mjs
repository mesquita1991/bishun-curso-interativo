import assert from 'node:assert/strict';
import '../aprendizagem-v8.js';
const x=globalThis.BishunLearning,D=x.DAY,t=10000000;
const first=x.review({},2,t);
assert.equal(first.verifiedLevel,1);
assert.equal(first.due,t+D);
const immediate=x.review(first.record,2,t+100);
assert.equal(immediate.promoted,false);
assert.equal(immediate.due,first.due);
const next=x.review(immediate.record,2,first.due);
assert.equal(next.verifiedLevel,2);
assert.equal(next.due,t+4*D);
assert.equal(x.review(next.record,0,next.due).verifiedLevel,0);
assert.equal(x.review({level:5,attempts:100},2,t).record.historicalLevel,5);
assert.equal(x.category(undefined),'new');
assert.equal(x.category({attempts:1,due:t},t),'due');
const groups=x.partition([{type:'char',id:'我'},{type:'char',id:'你'}],{char:{'你':{attempts:1,due:t+D}}},t);
assert.equal(groups.new.length,1);
assert.equal(groups.learning.length,1);
let w=x.writing({},'八',3,t);
assert.equal(w.writingResults['八'].passed,false);
w=x.writing(w,'八',1,t+1);
assert.equal(w.writingResults['八'].passed,true);
assert.deepEqual(w.writtenChars,['八']);
const p={retentionDueAt:t,initialPassedAt:t-D};
const o=x.objective(p,9,10,t);
assert.equal(o.recorded,true);
const s={...p,...o};
assert.equal(x.retentionStatus(s,t).phase,'observed');
const o2=x.objective(s,9,10,t+3*D);
assert.equal(o2.consolidated,true);
assert.equal(x.retentionStatus({...s,...o2},t+3*D).phase,'consolidated');
assert.equal(x.objective({retentionDueAt:t,initialPassedAt:t},10,10,t).recorded,false);
assert.equal(x.retentionStatus({retentionDueAt:t,retentionCheckedAt:t+1,retentionRemembered:10,retentionTotal:10},t+1).phase,'due');
console.log('Motor v8: separação temporal, escrita, filas, migração e avaliações verificadas');
